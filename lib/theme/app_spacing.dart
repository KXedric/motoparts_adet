/// MotoParts Manager spacing constants.
/// Base unit: 4px.
class AppSpacing {
  AppSpacing._();

  /// Extra small — 4px
  static const double xs = 4;

  /// Small — 8px
  static const double sm = 8;

  /// Medium — 16px (gap between list items)
  static const double md = 16;

  /// Large — 24px (screen edge padding, section gaps)
  static const double lg = 24;

  /// Extra large — 32px
  static const double xl = 32;
}
